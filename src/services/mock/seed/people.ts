function membership(
  id: string,
  memberId: string,
  cycleId: string,
  role: Membership['role'],
  /** Named by function here; stored as the id of this EJ's area for it. */
  directorate: keyof typeof WORK_AREA_ID_BY_DIRECTORATE,
  weeklyHours: number,
  /** For whoever joined after the management had already started. */
  joinedAt?: string,
): Membership {
  const isPrevious = cycleId === PREVIOUS_CYCLE_ID
  return {
    id,
    memberId,
    cycleId,
    role,
    workAreaId: WORK_AREA_ID_BY_DIRECTORATE[directorate],
    weeklyHours,
    startsAt: joinedAt ?? (isPrevious ? '2025-02-03' : '2026-02-02'),
    endsAt: isPrevious ? '2025-12-19' : null,
    createdAt: isPrevious ? '2025-02-03' : '2026-02-02',
  }
}
